export type Translations = typeof translations.ar;

interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  dir: "rtl" | "ltr";
  isRTL: boolean;
  t: (typeof translations)[Language];
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY = "fasl_language";

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("ar");

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as Language | null;
      if (stored && (stored === "ar" || stored === "fr" || stored === "en")) {
        setLanguageState(stored);
      }
    } catch {
      // localStorage not accessible
    }
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // localStorage not accessible
    }
  };

  const currentOption = useMemo(
    () => SUPPORTED_LANGUAGES.find((l) => l.code === language) ?? SUPPORTED_LANGUAGES[0],
    [language],
  );

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = currentOption.code;
      document.documentElement.dir = currentOption.dir;
    }
  }, [currentOption]);

  const value = useMemo<I18nContextType>(
    () => ({
      language,
      setLanguage,
      dir: currentOption.dir,
      isRTL: currentOption.dir === "rtl",
      t: (translations[language] || translations.ar) as (typeof translations)[Language],
    }),
    [language, currentOption],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextType {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Fallback for SSR / outside provider
    return {
      language: "ar",
      setLanguage: () => {},
      dir: "rtl",
      isRTL: true,
      t: translations.ar,
    };
  }
  return ctx;
}
